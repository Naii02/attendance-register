import datetime

attendees = []

def get_date_time():
    now = datetime.datetime.now()
    return now.strftime("%d/%m/%Y %H:%M:%S")

def register_attendance():
    try:
        first_name = input("Enter you first name: ").strip()
        last_name = input("Enter you last name: ").strip()

        if first_name == ""or last_name == "":
            raise ValueError("First name and last name cannot be empty")

        if not first_name.replace(" ", "").isalpha() or not last_name.replace(" ","").isalpha():
            raise ValueError("Names can only contain letters")

        date_time = get_date_time()

        #dictionary
        participant = {
            "first_name": first_name,
            "last_name": last_name,
            "date_time": date_time
        }

        #add to the list
        attendees.append(participant)

        print("\nAttendance registered succesfully!")
        print(f"Participant: {first_name} {last_name}")
        print(f"Arrival: {date_time}")

    except ValueError as error:
        print(f"Error: {error}")

def generate_report():
    print("\n ===== ATTENDANCE REPORT =====\n")

    if len(attendees) == 0:
        print("No attendees registered yet")
        return

    for number, participant in enumerate(attendees, start=1):
        print(f"{number}. {participant['first_name']} {participant['last_name']} - Arrival: {participant['date_time']}")

    print(f"\nTotal attendees: {len(attendees)}")

def main():
    while True:
        print("\n===== ATTENDANCE SYSTEM =====\n")
        print("Register attendance [1]")
        print("Generate report     [2]")
        print("EXIT                [3]")

        option = input("Choose an option: ").strip()

        match option:
            case "1":
                register_attendance()
            case "2":
                generate_report()
            case "3":
                print("Exiting the program...")
                break
            case _:
                print("Invalid option, please try again")

main()